    /** 根据票据全文 + 商家名，返回归类名称 */
    fun classify(rawText: String, type: String, merchant: String?): String {
        val rules = if (type == "income") INCOME_RULES else EXPENSE_RULES
        val haystack = (rawText + " " + (merchant.orEmpty())).lowercase()

        for (rule in rules) {
            if (rule.keywords.any { haystack.contains(it) }) return rule.name
        }
        return if (type == "income") "其他收入" else "其他支出"
    }
